export const issueCaseDecision = async (req, res, next) => {
  try {
    const { id } = req.params;
    const { decision_type, penalty_days, effective_date, decision_summary, send_notice } = req.body;

    if (!decision_type) {
      return res.status(400).json({
        success: false,
        message: 'decision_type is required',
      });
    }

    const decisionId = await addDecision({
      caseId: id,
      decisionType: decision_type,
      penaltyDays: penalty_days || null,
      effectiveDate: effective_date || null,
      decisionSummary: decision_summary || null,
      approvedBy: req.user?.user_id || null,
      sendNotice: Boolean(send_notice),
    });

    return res.status(201).json({
      success: true,
      message: 'Decision recorded',
      data: { id: decisionId },
    });
  } catch (error) {
    if (error.code === 'DUE_PROCESS_NTE_REQUIRED' || error.code === 'DUE_PROCESS_RESPONSE_REQUIRED') {
      return res.status(400).json({
        success: false,
        message: error.message,
      });
    }
    logger.error('Issue case decision error:', error);
    next(error);
  }
};

export const getMyDueProcessNotices = async (req, res, next) => {
  try {
    const employeeId = req.user?.employee_id;
    if (!employeeId) {
      return res.status(403).json({
        success: false,
        message: 'Employee context required',
      });
    }

    const notices = await db.getAll(
      `SELECT cn.*, dc.case_number
       FROM case_notices cn
       JOIN disciplinary_cases dc ON cn.case_id = dc.id
       WHERE cn.recipient_employee_id = ?
       ORDER BY cn.created_at DESC`,
      [employeeId]
    );

    return res.json({
      success: true,
      data: notices,
      count: notices.length,
    });
  } catch (error) {
    logger.error('Get my due process notices error:', error);
    next(error);
  }
};


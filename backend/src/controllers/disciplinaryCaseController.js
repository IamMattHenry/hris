export const submitCaseExplanation = async (req, res, next) => {
  try {
    const { id } = req.params;
    const { explanation_text, attachment_url } = req.body;
    const employeeId = req.user?.employee_id;

    if (!employeeId) {
      return res.status(403).json({
        success: false,
        message: 'Employee context required',
      });
    }

    if (!explanation_text) {
      return res.status(400).json({
        success: false,
        message: 'explanation_text is required',
      });
    }

    const caseRow = await db.getOne(
      'SELECT employee_id FROM disciplinary_cases WHERE id = ?',
      [id]
    );

    if (!caseRow || Number(caseRow.employee_id) !== Number(employeeId)) {
      return res.status(403).json({
        success: false,
        message: 'You are not authorized to submit an explanation for this case',
      });
    }

    const explanationId = await submitExplanation({
      caseId: id,
      employeeId,
      explanationText: explanation_text,
      attachmentUrl: attachment_url || null,
    });

    return res.status(201).json({
      success: true,
      message: 'Explanation submitted',
      data: { id: explanationId },
    });
  } catch (error) {
    logger.error('Submit case explanation error:', error);
    next(error);
  }
};


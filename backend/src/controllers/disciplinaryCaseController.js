export const createDisciplinaryCaseManual = async (req, res, next) => {
  try {
    const { employee_id, case_type, severity, assigned_hr_id, assigned_manager_id } = req.body;

    if (!employee_id) {
      return res.status(400).json({
        success: false,
        message: 'employee_id is required',
      });
    }

    const createdBy = req.user?.user_id || null;
    const result = await createDisciplinaryCase({
      employeeId: employee_id,
      caseType: case_type || 'attendance',
      severity: severity || null,
      assignedHrId: assigned_hr_id || null,
      assignedManagerId: assigned_manager_id || null,
      createdBy,
    });

    return res.status(201).json({
      success: true,
      message: 'Case created successfully',
      data: result,
    });
  } catch (error) {
    logger.error('Create disciplinary case error:', error);
    next(error);
  }
};

export const updateDisciplinaryCase = async (req, res, next) => {
  try {
    const { id } = req.params;
    const { status, severity, assigned_hr_id, assigned_manager_id } = req.body;

    const updates = {};
    if (status) updates.status = status;
    if (severity !== undefined) updates.severity = severity;
    if (assigned_hr_id !== undefined) updates.assigned_hr_id = assigned_hr_id || null;
    if (assigned_manager_id !== undefined) updates.assigned_manager_id = assigned_manager_id || null;

    if (Object.keys(updates).length === 0) {
      return res.status(400).json({
        success: false,
        message: 'No updates provided',
      });
    }

    const updated = await updateCase({
      caseId: id,
      updates,
      updatedBy: req.user?.user_id || null,
      ipAddress: req.ip,
    });

    if (!updated) {
      return res.status(404).json({
        success: false,
        message: 'Case not found',
      });
    }

    return res.json({
      success: true,
      message: 'Case updated',
    });
  } catch (error) {
    logger.error('Update disciplinary case error:', error);
    next(error);
  }
};

export const createCaseNoticeHandler = async (req, res, next) => {
  try {
    const { id } = req.params;
    const {
      notice_type,
      subject,
      content,
      sent_via,
      due_date,
      send_now,
    } = req.body;

    if (!notice_type || !subject || !content) {
      return res.status(400).json({
        success: false,
        message: 'notice_type, subject, and content are required',
      });
    }

    const caseRow = await db.getOne('SELECT employee_id FROM disciplinary_cases WHERE id = ?', [id]);
    if (!caseRow) {
      return res.status(404).json({
        success: false,
        message: 'Case not found',
      });
    }

    const noticeId = await createCaseNotice({
      caseId: id,
      noticeType: notice_type,
      subject,
      content,
      recipientEmployeeId: caseRow.employee_id,
      sentVia: sent_via || 'internal',
      dueDate: due_date || null,
      createdBy: req.user?.user_id || null,
      autoGenerated: false,
      sendNow: Boolean(send_now),
    });

    return res.status(201).json({
      success: true,
      message: 'Notice created',
      data: { id: noticeId },
    });
  } catch (error) {
    logger.error('Create case notice error:', error);
    next(error);
  }
};

